// generatedHeader marks the files owned by the generator. Generate only
// removes stale files that start with it.
const generatedHeader = "// Code generated by inject; DO NOT EDIT."

// GeneratorOptions tells the generator where the application lives and where
// the generated code goes.
type GeneratorOptions struct {
	// ModulePath is the Go module path of the application ("module" in go.mod).
	ModulePath string
	// ModuleDir is the absolute root directory of that module.
	ModuleDir string
	// OutputDir is the absolute directory that receives the generated code.
	// It must be inside ModuleDir so the generated packages can be imported.
	OutputDir string
}

// Generator writes one fx module per component of the graph, mirroring the
// import path of the annotated function under OutputDir, plus a root
// module.go whose Module() includes all of them.
type Generator struct {
	opts  GeneratorOptions
	graph *graph.Graph[Component]
}

// NewGenerator returns a generator for the graph.
func NewGenerator(g *graph.Graph[Component], opts GeneratorOptions) *Generator {
	return &Generator{opts: opts, graph: g}
}

// Generate writes the generated files to OutputDir and removes generated
// files of previous runs that are no longer produced.
func (p *Generator) Generate(ctx context.Context) error {
	files, err := p.Render(ctx)
	if err != nil {
		return err
	}

	if err := removeStale(p.opts.OutputDir, files); err != nil {
		return err
	}

	for _, name := range sortedFileNames(files) {
		filePath := filepath.Join(p.opts.OutputDir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(filePath), os.ModePerm); err != nil {
			return errors.Wrap(err, errors.Internalf("error creating directory for %s", filePath))
		}
		if err := os.WriteFile(filePath, files[name], 0o644); err != nil {
			return errors.Wrap(err, errors.Internalf("error writing %s", filePath))
		}
		log.FromContext(ctx).Debugf("generated %s", filePath)
	}

	return nil
}

// Render returns the generated files keyed by their slash-separated path
// relative to OutputDir, without touching the disk.
func (p *Generator) Render(ctx context.Context) (map[string][]byte, error) {
	base, err := p.baseImport()
	if err != nil {
		return nil, err
	}

	tmpl, err := NewTemplate()
	if err != nil {
		return nil, err
	}

	files := map[string][]byte{}
	root := RootData{Package: packageIdent(filepath.Base(p.opts.OutputDir))}
	rootImports := map[string]struct{}{}

	for _, key := range p.graph.SortedKeys() {
		vertex := p.graph.Vertices[key]
		data, err := p.moduleData(base, vertex)
		if err != nil {
			return nil, err
		}

		name := path.Join(vertex.Value.Entry.Path, strings.ToLower(data.Func)+"_module.go")
		if _, exists := files[name]; exists {
			return nil, errors.AlreadyExistsf("two components generate %s; rename one of the functions", name)
		}

		src, err := render(tmpl, "module", data)
		if err != nil {
			return nil, errors.Wrap(err, errors.Internalf("error generating module of %s", key))
		}
		files[name] = src

		genImport := ImportData{Alias: genAlias(vertex.Value.Entry), Path: base + "/" + vertex.Value.Entry.Path}
		if _, ok := rootImports[genImport.Path]; !ok {
			rootImports[genImport.Path] = struct{}{}
			root.Imports = append(root.Imports, genImport)
		}
		root.Modules = append(root.Modules, genImport.Alias+"."+data.Func+"Module()")
	}

	src, err := render(tmpl, "root", root)
	if err != nil {
		return nil, errors.Wrap(err, errors.Internalf("error generating root module"))
	}
	files["module.go"] = src

	return files, nil
}

// baseImport returns the import path of OutputDir.
func (p *Generator) baseImport() (string, error) {
	if p.opts.ModulePath == "" || p.opts.ModuleDir == "" || p.opts.OutputDir == "" {
		return "", errors.NotValidf("module path, module dir and output dir are required")
	}

	rel, err := filepath.Rel(p.opts.ModuleDir, p.opts.OutputDir)
	if err != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
		return "", errors.NotValidf("output dir %s must be inside the module dir %s", p.opts.OutputDir, p.opts.ModuleDir)
	}
	if rel == "." {
		return "", errors.NotValidf("output dir must be a subdirectory of the module dir %s", p.opts.ModuleDir)
	}

	return path.Join(p.opts.ModulePath, filepath.ToSlash(rel)), nil
}

// moduleData collects what the module template needs for one component.
func (p *Generator) moduleData(base string, vertex *graph.Vertex[Component]) (ModuleData, error) {
	comp := vertex.Value
	entry := comp.Entry

	if entry.Package == "main" {
		return ModuleData{}, errors.NotValidf("%s is in package main, which cannot be imported; move it to another package", vertex.Key)
	}
	if !token.IsExported(entry.Func.Name) {
		return ModuleData{}, errors.NotValidf("%s must be exported to be used by the generated module", vertex.Key)
	}

	src := srcAlias(entry)
	data := ModuleData{
		Package: entry.Package,
		Func:    entry.Func.Name,
		Source:  entry.Path,
		Kind:    "Provide",
		Target:  target(src+"."+entry.Func.Name, comp),
		Imports: []ImportData{{Alias: src, Path: entry.Path}},
	}
	if comp.Type == AnnotationTypeINVOKE {
		data.Kind = "Invoke"
	}

	deps := vertex.Incoming()
	sort.Slice(deps, func(i, j int) bool { return deps[i].Key < deps[j].Key })

	imported := map[string]struct{}{}
	for _, dep := range deps {
		depEntry := dep.Value.Entry
		if depEntry.Path == entry.Path {
			data.Deps = append(data.Deps, depEntry.Func.Name+"Module()")
			continue
		}

		alias := genAlias(depEntry)
		data.Deps = append(data.Deps, alias+"."+depEntry.Func.Name+"Module()")
		if _, ok := imported[depEntry.Path]; !ok {
			imported[depEntry.Path] = struct{}{}
			data.Imports = append(data.Imports, ImportData{Alias: alias, Path: base + "/" + depEntry.Path})
		}
	}

	return data, nil
}

// target returns the expression given to fx.Provide/fx.Invoke, wrapping the
// function in fx.Annotate when a parameter or result has a name or group.
func target(fn string, comp Component) string {
	var opts []string

	if tags := tagList(comp.Injects); tags != "" {
		opts = append(opts, "fx.ParamTags("+tags+")")
	}
	if tags := tagList(comp.Provides); tags != "" {
		opts = append(opts, "fx.ResultTags("+tags+")")
	}

	if len(opts) == 0 {
		return fn
	}
	return "fx.Annotate(" + fn + ", " + strings.Join(opts, ", ") + ")"
}

// tagList returns the fx tags from index 0 up to the last tagged index, as Go
// string literals, or "" when no index has a tag.
func tagList(anns map[int]Annotation) string {
	last := -1
	for idx, ann := range anns {
		if ann.Tag() != "" && idx > last {
			last = idx
		}
	}
	if last < 0 {
		return ""
	}

	tags := make([]string, last+1)
	for i := range tags {
		ann := anns[i]
		tags[i] = goString(ann.Tag())
	}
	return strings.Join(tags, ", ")
}

// goString quotes s as a raw string literal when it can, so a tag reads as
// `name:"x"` instead of "name:\"x\"".
func goString(s string) string {
	if s != "" && !strings.Contains(s, "`") {
		return "`" + s + "`"
	}
	return fmt.Sprintf("%q", s)
}

func render(tmpl *template.Template, name string, data any) ([]byte, error) {
	var buf bytes.Buffer
	if err := tmpl.ExecuteTemplate(&buf, name, data); err != nil {
		return nil, errors.Wrap(err, errors.Internalf("error executing template %s", name))
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, errors.Wrap(err, errors.Internalf("error formatting generated source:\n%s", buf.String()))
	}
	return formatted, nil
}

// removeStale deletes generated files under dir that are not in keep, then
// removes the directories left empty.
func removeStale(dir string, keep map[string][]byte) error {
	if _, err := os.Stat(dir); os.IsNotExist(err) {
		return nil
	}

	var dirs []string
	err := filepath.WalkDir(dir, func(p string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			dirs = append(dirs, p)
			return nil
		}
		if filepath.Ext(p) != ".go" {
			return nil
		}

		rel, err := filepath.Rel(dir, p)
		if err != nil {
			return err
		}
		if _, ok := keep[filepath.ToSlash(rel)]; ok {
			return nil
		}

		content, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		if bytes.HasPrefix(content, []byte(generatedHeader)) {
			return os.Remove(p)
		}
		return nil
	})
	if err != nil {
		return errors.Wrap(err, errors.Internalf("error removing stale generated files in %s", dir))
	}

	// deepest first, so parents are empty when we reach them
	sort.Sort(sort.Reverse(sort.StringSlice(dirs)))
	for _, d := range dirs {
		if entries, err := os.ReadDir(d); err == nil && len(entries) == 0 && d != dir {
			_ = os.Remove(d)
		}
	}

	return nil
}

func sortedFileNames(files map[string][]byte) []string {
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

var nonIdent = regexp.MustCompile(`[^A-Za-z0-9_]`)

// packageIdent turns a directory name into a valid package name.
func packageIdent(name string) string {
	name = nonIdent.ReplaceAllString(name, "_")
	if name == "" || (name[0] >= '0' && name[0] <= '9') {
		name = "_" + name
	}
	return name
}

// srcAlias is the import alias of the package that declares the function.
func srcAlias(entry annotation.Entry) string {
	return "src_" + packageIdent(entry.Package) + "_" + shortHash(entry.Path)
}

// genAlias is the import alias of the generated package of the function.
func genAlias(entry annotation.Entry) string {
	return "gen_" + packageIdent(entry.Package) + "_" + shortHash(entry.Path)
}

func shortHash(s string) string {
	sum := md5.Sum([]byte(s))
	return hex.EncodeToString(sum[:])[:8]
}

package builder

import (
	"context"
	"fmt"
	"path"
	"path/filepath"
	"strings"

	"github.com/xgodev/boost/fx/modules/extra/multiserver"
	"github.com/xgodev/boost/inject"
	"github.com/xgodev/boost/model/errors"
)

// generatedHeader marks the files owned by builder. Generate only removes
// stale files that start with it.
const generatedHeader = "// Code generated by builder; DO NOT EDIT."

// outputDir is the directory under GeneratorOptions.OutputDir that receives
// one package per app.
const outputDir = "builder"

// Import paths and aliases of the boost packages the generated doors use.
const (
	contextPath       = "context"
	boostEchoPath     = "github.com/xgodev/boost/factory/contrib/labstack/echo/v4"
	echoFxPath        = "github.com/xgodev/boost/fx/modules/factory/contrib/labstack/echo/v4"
	grpcServerPath    = "github.com/xgodev/boost/factory/contrib/google.golang.org/grpc/v1/server"
	grpcFxPath        = "github.com/xgodev/boost/fx/modules/factory/contrib/google.golang.org/grpc/v1/server"
	multiserverPath   = "github.com/xgodev/boost/extra/multiserver"
	multiserverFxPath = "github.com/xgodev/boost/fx/modules/extra/multiserver"
	contextFxPath     = "github.com/xgodev/boost/fx/modules/core/context"
	functionPath      = "github.com/xgodev/boost/bootstrap/function"
	functionFxPath    = "github.com/xgodev/boost/fx/modules/bootstrap/function"
)

// Generator writes, under OutputDir/builder/<app>, one fx module per door of
// the app (a REST or gRPC server, or the function) and a modules.go whose
// Modules() returns all of them.
type Generator struct {
	spec *Spec
	opts inject.GeneratorOptions
}

// NewGenerator returns a generator for the spec. opts are the options of the
// inject generator of the same application: the doors include the inject
// modules generated under the same OutputDir.
func NewGenerator(spec *Spec, opts inject.GeneratorOptions) *Generator {
	return &Generator{spec: spec, opts: opts}
}

// Generate writes the generated files under OutputDir/builder and removes the
// builder files of previous runs that are no longer produced.
func (g *Generator) Generate(ctx context.Context) error {
	files, err := g.Render(ctx)
	if err != nil {
		return err
	}

	rel := make(map[string][]byte, len(files))
	for name, src := range files {
		rel[strings.TrimPrefix(name, outputDir+"/")] = src
	}
	return inject.WriteGenerated(ctx, filepath.Join(g.opts.OutputDir, outputDir), rel, generatedHeader)
}

// Render returns the generated files keyed by their slash-separated path
// relative to OutputDir (builder/<app>/...), without touching the disk.
func (g *Generator) Render(context.Context) (map[string][]byte, error) {
	base, err := g.opts.BaseImport()
	if err != nil {
		return nil, err
	}
	tmpl, err := newTemplate()
	if err != nil {
		return nil, err
	}

	files := map[string][]byte{}
	for _, app := range g.spec.Apps {
		mods := modulesData{Header: generatedHeader, Package: app.Name, Servers: len(app.Servers) > 0}

		var doors []doorData
		for _, srv := range app.Servers {
			door, err := serverDoor(base, srv)
			if err != nil {
				return nil, err
			}
			doors = append(doors, door)
		}
		if app.Function != nil {
			door, err := functionDoor(base, app.Name, *app.Function)
			if err != nil {
				return nil, err
			}
			doors = append(doors, door)
		}

		for _, door := range doors {
			src, err := inject.ExecuteTemplate(tmpl, "door", door)
			if err != nil {
				return nil, errors.Wrap(err, errors.Internalf("error generating door %s", door.Name))
			}
			files[path.Join(outputDir, app.Name, door.Var+"_module.go")] = src
			mods.Modules = append(mods.Modules, door.Func+"Module()")
		}

		if mods.Servers {
			mods.Imports = []inject.ImportData{{Alias: "multiserverfx", Path: multiserverFxPath}}
			mods.Modules = append(mods.Modules, "multiserverfx.Module()")
		}
		src, err := inject.ExecuteTemplate(tmpl, "modules", mods)
		if err != nil {
			return nil, errors.Wrap(err, errors.Internalf("error generating modules of app %s", app.Name))
		}
		files[path.Join(outputDir, app.Name, "modules.go")] = src
	}

	return files, nil
}

// door starts the data of a door file named name in app.
func door(app, name, doc string) doorData {
	return doorData{
		Header:  generatedHeader,
		Package: app,
		Var:     name,
		Func:    strings.ToUpper(name[:1]) + name[1:],
		Doc:     doc,
		Name:    app + "." + name,
	}
}

// isDefault reports whether the server is the one the shipped echo or gRPC
// fx module builds from the factory's own config.
func isDefault(srv Server) bool {
	return (srv.Kind == KindREST && srv.Name == defaultRESTServer) || (srv.Kind == KindGRPC && srv.Name == defaultGRPCServer)
}

// configPath is the config path of a named server.
func configPath(srv Server) string {
	return srv.App + ".server." + srv.Name
}

func serverDoor(base string, srv Server) (doorData, error) {
	imps := newImports()
	var (
		d         doorData
		serverPkg string
		params    []string
		body      []string
		modules   []string
	)

	include := func(entry inject.Component) {
		imp, call := inject.ModuleOf(base, entry.Entry)
		imps.add(imp.Alias, imp.Path)
		for _, m := range modules {
			if m == call {
				return
			}
		}
		modules = append(modules, call)
	}

	switch srv.Kind {
	case KindREST:
		d = door(srv.App, srv.Name, fmt.Sprintf("serves the REST routes of server %s on echo.", srv.Name))
		serverPkg = imps.add("boostecho", boostEchoPath)

		receivers := map[string]string{} // receiver type and path -> parameter
		for _, route := range srv.Routes {
			fn, err := handlerFunc(imps, route.Handler, receivers, &params, include)
			if err != nil {
				return doorData{}, err
			}
			body = append(body, fmt.Sprintf("srv.Add(%q, %q, %s)", route.Method, route.Path, fn))
		}
	case KindGRPC:
		d = door(srv.App, srv.Name, fmt.Sprintf("serves the gRPC services of server %s.", srv.Name))
		serverPkg = imps.add("grpcserver", grpcServerPath)

		for i, svc := range srv.Services {
			entry := svc.Provider.Entry
			tp, err := imps.qualify(entry, entry.Func.Results[svc.Index].Type)
			if err != nil {
				return doorData{}, err
			}
			register, err := imps.qualify(entry, svc.Register)
			if err != nil {
				return doorData{}, err
			}
			include(svc.Provider)
			param := fmt.Sprintf("s%d", i)
			params = append(params, param+" "+tp)
			body = append(body, fmt.Sprintf("%s(srv.ServiceRegistrar(), %s)", register, param))
		}
	}

	invoke := "func(srv *" + serverPkg + ".Server" + joinPrefixed(params) + ") {\n" + strings.Join(body, "\n") + "\n}"

	if isDefault(srv) {
		alias, fxPath := "echofx", echoFxPath
		if srv.Kind == KindGRPC {
			alias, fxPath = "grpcfx", grpcFxPath
		}
		fxModule := imps.add(alias, fxPath)
		d.Options = append(d.Options, fxModule+".Module()")
		d.Options = append(d.Options, modules...)
		d.Options = append(d.Options, "fx.Invoke("+invoke+")")
		d.Imports = imps.sorted()
		return d, nil
	}

	// a named server is built from its own config path and only takes the
	// plugins provided under its name
	named := goTag(`name:"` + srv.Name + `"`)
	d.Init = []string{fmt.Sprintf("%s.ConfigAdd(%q)", serverPkg, configPath(srv))}

	ctxPkg := imps.add("context", contextPath)
	constructor := fmt.Sprintf("func(ctx %s.Context, plugins []%s.Plugin) (*%s.Server, error) {\n", ctxPkg, serverPkg, serverPkg)
	if srv.Kind == KindREST {
		constructor += fmt.Sprintf("return %s.NewServerWithConfigPath(ctx, %q, plugins...)\n}", serverPkg, configPath(srv))
	} else {
		constructor += fmt.Sprintf("opts, err := %s.NewOptionsWithPath(%q)\nif err != nil {\nreturn nil, err\n}\n", serverPkg, configPath(srv)) +
			fmt.Sprintf("return %s.NewServerWithOptions(ctx, opts, plugins...), nil\n}", serverPkg)
	}
	server := imps.add("multiserver", multiserverPath)

	d.Options = append(d.Options,
		imps.add("contextfx", contextFxPath)+".Module()",
		"fx.Provide(\n"+
			"fx.Annotate(\n"+constructor+",\n"+
			"fx.ParamTags(``, "+goTag(`name:"`+srv.Name+`" optional:"true"`)+"),\n"+
			"fx.ResultTags("+named+"),\n),\n"+
			"fx.Annotate(\n"+
			"func(srv *"+serverPkg+".Server) "+server+".Server {\nreturn srv\n},\n"+
			"fx.ParamTags("+named+"),\n"+
			"fx.ResultTags("+goTag(`group:"`+multiserver.ServersGroupKey+`"`)+"),\n),\n)",
	)
	d.Options = append(d.Options, modules...)
	d.Options = append(d.Options, "fx.Invoke(fx.Annotate(\n"+invoke+",\nfx.ParamTags("+named+"),\n))")
	d.Imports = imps.sorted()
	return d, nil
}

func functionDoor(base, app string, fn Function) (doorData, error) {
	d := door(app, functionFile, fmt.Sprintf("runs the @Function handler with the %s adapter.", fn.Adapter))
	imps := newImports()
	entry := fn.Handler.Entry

	result, err := imps.qualify(entry, entry.Func.Results[0].Type)
	if err != nil {
		return doorData{}, err
	}

	var params []string
	var modules []string
	call, err := handlerFunc(imps, fn.Handler, map[string]string{}, &params, func(provider inject.Component) {
		imp, mod := inject.ModuleOf(base, provider.Entry)
		imps.add(imp.Alias, imp.Path)
		modules = append(modules, mod)
	})
	if err != nil {
		return doorData{}, err
	}

	handlerType := imps.add("bsfunction", functionPath) + ".Handler[" + result + "]"
	d.Options = append(d.Options, modules...)
	d.Options = append(d.Options,
		"fx.Provide(func("+strings.Join(params, ", ")+") "+handlerType+" {\nreturn "+call+"\n})",
		imps.add("functionfx", functionFxPath)+".Module["+result+"](nil)",
	)
	for _, adapter := range functionAdapters[fn.Adapter] {
		d.Options = append(d.Options, imps.add(adapter.Alias, adapter.Path)+".Module["+result+"]()")
	}
	d.Imports = imps.sorted()
	return d, nil
}

// handlerFunc returns the expression of the handler: pkg.Func, or h<N>.Method
// with h<N> a parameter of the receiver type, added to params the first time
// the receiver is seen and whose provider module is passed to include.
func handlerFunc(imps *imports, h Handler, receivers map[string]string, params *[]string, include func(inject.Component)) (string, error) {
	entry := h.Entry
	if h.Receiver == nil {
		return imps.source(entry.Package, entry.Path) + "." + entry.Func.Name, nil
	}

	key := h.Receiver.Type + " " + entry.Path
	param, seen := receivers[key]
	if !seen {
		tp, err := imps.qualify(entry, h.Receiver.Type)
		if err != nil {
			return "", err
		}
		param = fmt.Sprintf("h%d", len(receivers))
		receivers[key] = param
		*params = append(*params, param+" "+tp)
		include(h.Receiver.Provider)
	}
	return param + "." + entry.Func.Name, nil
}

// joinPrefixed returns ", a, b" for [a b], and "" for none.
func joinPrefixed(list []string) string {
	if len(list) == 0 {
		return ""
	}
	return ", " + strings.Join(list, ", ")
}

// goTag quotes an fx tag as a raw string literal.
func goTag(tag string) string {
	return "`" + tag + "`"
}

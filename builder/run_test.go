// fixture writes a module with the given package files under a temp dir and
// returns its root.
func fixture(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	files["go.mod"] = "module example.com/fixture\n\ngo 1.21\n"
	for name, body := range files {
		writeFile(t, filepath.Join(root, filepath.FromSlash(name)), body)
	}
	return root
}

func writeFile(t *testing.T, p, body string) {
	t.Helper()
	require.NoError(t, os.MkdirAll(filepath.Dir(p), 0o755))
	require.NoError(t, os.WriteFile(p, []byte(body), 0o644))
}

// validApp is an app with an inject module and a REST door.
func validApp() map[string]string {
	return map[string]string{
		"app/app.go": `package app

// the alias names the package without loading it: the fixture has no go.sum
import echo "github.com/labstack/echo/v4"

// New provides the value.
// @Provide(index=0)
func New() *Value { return &Value{} }

// Value is provided.
type Value struct{}

// Get answers with the value.
// @REST(method=GET, path=/value)
func Get(c echo.Context) error { return nil }
`,
	}
}

func TestGenerate_InvalidAnnotationWritesNothing(t *testing.T) {
	root := fixture(t, map[string]string{
		"app/app.go": `package app

// New provides the value.
// @Provide(index=0)
func New() *Value { return &Value{} }

// Value is provided.
type Value struct{}

// Fetch is not a REST method.
// @REST(method=FETCH, path=/x)
func Fetch() {}
`,
	})
	out := filepath.Join(root, "gen")
	stale := filepath.Join(out, "module.go")
	writeFile(t, stale, "// Code generated by inject; DO NOT EDIT.\n\npackage gen\n")

	cmd := filepath.Join(root, "cmd")
	err := Generate(context.Background(), root, out, cmd)
	require.Error(t, err)
	assert.True(t, errors.IsNotValid(err), "got %v", err)

	got, err := os.ReadFile(stale)
	require.NoError(t, err)
	assert.Contains(t, string(got), "package gen\n", "the previous output is untouched")
	entries, err := os.ReadDir(out)
	require.NoError(t, err)
	assert.Len(t, entries, 1, "nothing else is written")
	assert.NoDirExists(t, cmd, "no main is written")
}

func TestGenerate_WritesInjectModulesDoorsAndMains(t *testing.T) {
	root := fixture(t, validApp())
	out := filepath.Join(root, "gen")
	cmd := filepath.Join(root, "cmd")

	require.NoError(t, Generate(context.Background(), root, out, cmd))

	assert.FileExists(t, filepath.Join(out, "module.go"))
	assert.FileExists(t, filepath.Join(out, "app", "new_module.go"))
	assert.FileExists(t, filepath.Join(out, "builder", "api", "modules.go"))
	main, err := os.ReadFile(filepath.Join(cmd, "api", "main.go"))
	require.NoError(t, err, "every app gets its main")
	assert.Contains(t, string(main), `"example.com/fixture/gen/builder/api"`)
	assert.Contains(t, string(main), "app.Modules()")
}

func TestGenerate_WithoutCmdWritesNoMain(t *testing.T) {
	root := fixture(t, validApp())

	require.NoError(t, Generate(context.Background(), root, filepath.Join(root, "gen"), ""))

	assert.FileExists(t, filepath.Join(root, "gen", "builder", "api", "modules.go"))
	assert.NoDirExists(t, filepath.Join(root, "cmd"))
}

func TestStale_NothingAfterGenerate(t *testing.T) {
	root := fixture(t, validApp())
	t.Chdir(root)
	ctx := context.Background()
	require.NoError(t, Generate(ctx, ".", "gen", "cmd"))

	stale, err := Stale(ctx, ".", "gen", "cmd")
	require.NoError(t, err)
	assert.Empty(t, stale)
}

func TestStale_ListsWhatGenerateWouldChange(t *testing.T) {
	root := fixture(t, validApp())
	out := filepath.Join(root, "gen")
	cmd := filepath.Join(root, "cmd")
	ctx := context.Background()
	require.NoError(t, Generate(ctx, root, out, cmd))

	edited := filepath.Join(out, "module.go")
	writeFile(t, edited, "// Code generated by inject; DO NOT EDIT.\n\npackage gen\n")
	require.NoError(t, os.Remove(filepath.Join(cmd, "api", "main.go")))
	writeFile(t, filepath.Join(out, "old", "old_module.go"), "// Code generated by inject; DO NOT EDIT.\n\npackage old\n")
	writeFile(t, filepath.Join(out, "builder", "gone", "modules.go"), "// Code generated by builder; DO NOT EDIT.\n\npackage gone\n")
	writeFile(t, filepath.Join(out, "notes.go"), "package gen\n")
	writeFile(t, filepath.Join(cmd, "tool", "main.go"), "package main\n\nfunc main() {}\n")

	stale, err := Stale(ctx, root, out, cmd)
	require.NoError(t, err)
	assert.Equal(t, []string{
		"cmd/api/main.go",
		"gen/builder/gone/modules.go",
		"gen/module.go",
		"gen/old/old_module.go",
	}, stale, "changed, missing and left-over generated files; handwritten files are not generated")

	got, err := os.ReadFile(edited)
	require.NoError(t, err)
	assert.Equal(t, "// Code generated by inject; DO NOT EDIT.\n\npackage gen\n", string(got), "Stale writes nothing")
	assert.NoFileExists(t, filepath.Join(cmd, "api", "main.go"), "Stale writes nothing")
}

